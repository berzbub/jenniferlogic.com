import SwiftUI
import SwiftData
import UserNotifications


/// Opens the patient's phone dialer when the staff taps a "Call Patient" notification.
final class NotificationDelegate: NSObject, UNUserNotificationCenterDelegate {
    func userNotificationCenter(_ center: UNUserNotificationCenter,
                                didReceive response: UNNotificationResponse,
                                withCompletionHandler completionHandler: @escaping () -> Void) {
        if let link = response.notification.request.content.userInfo["callURL"] as? String,
           link.hasPrefix("tel:"),
           let url = URL(string: link) {
            DispatchQueue.main.async { UIApplication.shared.open(url) }
        }
        completionHandler()
    }

    func userNotificationCenter(_ center: UNUserNotificationCenter,
                                willPresent notification: UNNotification,
                                withCompletionHandler completionHandler: @escaping (UNNotificationPresentationOptions) -> Void) {
        completionHandler([.banner, .sound])
    }
}

@main
struct GoldenHarbourApp: App {
    private let notificationDelegate = NotificationDelegate()

    init() {
        UNUserNotificationCenter.current().delegate = notificationDelegate
    }

    var body: some Scene {
        WindowGroup {
            GoldenHarbourMainView()
        }
        .modelContainer(for: [Patient.self, MedicineItem.self, Appointment.self, ClinicalNote.self, InventoryAudit.self])
    }
}
